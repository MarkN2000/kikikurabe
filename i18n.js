export function resolveLanguage(languages = []) {
  for (const language of languages) {
    const base = String(language).toLowerCase().split('-')[0];
    if (base === 'ja' || base === 'en') return base;
  }
  return 'en';
}

// ブラウザのページとWorkerは同じ優先言語を参照する。Nodeでの既存チェックは日本語を使う。
export const locale = typeof window === 'undefined' && typeof WorkerGlobalScope === 'undefined'
  ? 'ja' : resolveLanguage(globalThis.navigator?.languages?.length ? navigator.languages : [globalThis.navigator?.language]);

export function t(message, ...values) {
  const translated = locale === 'en' ? english[message] ?? message : message;
  return translated.replace(/\{(\d+)\}/g, (match, index) => index < values.length ? String(values[index]) : match);
}

export function localizePage(root = document) {
  root.documentElement.lang = locale;
  for (const element of root.querySelectorAll('[data-i18n]')) element.textContent = t(element.textContent);
  for (const attribute of ['aria-label', 'title', 'content']) {
    for (const element of root.querySelectorAll(`[data-i18n-${attribute}]`)) {
      element.setAttribute(attribute, t(element.getAttribute(attribute)));
    }
  }
  root.querySelector('meta[property="og:locale"]').content = locale === 'ja' ? 'ja_JP' : 'en_US';
}
